import { getPurchaseRfq, updatePurchaseRfq } from "@vercentlabs/api";

import { procurementMutation, procurementRead } from "@/features/procurement/shared/route-helpers";
import { bodySchema } from "@/features/procurement/suppliers/server/supplier-http";


// One RFQ with its lines, suppliers and their quotations; changing a draft (or adding suppliers once sent).
type Params = { params: Promise<{ id: string }> };

export async function GET(request: Request, ctx: Params) {
  const { id } = await ctx.params;
  return procurementRead(request, async (client, context) => getPurchaseRfq(client, context, id));
}

export async function PATCH(request: Request, ctx: Params) {
  const { id } = await ctx.params;
  return procurementMutation(request, bodySchema, async (client, context, input) => ({ result: await updatePurchaseRfq(client, context, id, input) }));
}
