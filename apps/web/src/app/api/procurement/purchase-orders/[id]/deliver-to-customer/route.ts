import { confirmDropshipDelivery } from "@vercentlabs/api";

import { procurementMutation } from "@/features/procurement/shared/route-helpers";
import { bodySchema } from "@/features/procurement/suppliers/server/supplier-http";

// A dropship order delivered by the supplier to the customer: the goods receipt and the sales delivery in one step.
type Params = { params: Promise<{ id: string }> };

export async function POST(request: Request, ctx: Params) {
  const { id } = await ctx.params;
  return procurementMutation(request, bodySchema, async (client, context, input) => ({ result: await confirmDropshipDelivery(client, context, id, input) }));
}
