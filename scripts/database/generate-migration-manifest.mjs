#!/usr/bin/env node
// Writes packages/database/src/migration-manifest.js: the expand migrations
// this build expects (readiness refuses traffic until they are applied) and
// the contract migrations it knows. `--check` fails when the file is stale
// (run by verify:db), so a new migration cannot ship without it.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const list = (scope, kind) => {
  const directory = path.join(root, "database", scope, kind);
  return fs.existsSync(directory) ? fs.readdirSync(directory).filter((name) => name.endsWith(".sql")).sort() : [];
};
const manifest = {
  platform: list("platform", "migrations"),
  tenant: list("tenant", "migrations"),
  contracts: { platform: list("platform", "contracts"), tenant: list("tenant", "contracts") },
};
const target = path.join(root, "packages/database/src/migration-manifest.js");
const source = `// GENERATED by scripts/database/generate-migration-manifest.mjs — do not edit.\nexport const EXPECTED_MIGRATIONS = Object.freeze(${JSON.stringify(manifest, null, 2)});\n`;
if (process.argv.includes("--check")) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== source) {
    console.error("packages/database/src/migration-manifest.js is stale. Run: pnpm db:manifest");
    process.exit(1);
  }
  console.log(`Migration manifest current (${manifest.platform.length} platform, ${manifest.tenant.length} tenant, ${manifest.contracts.platform.length + manifest.contracts.tenant.length} contract).`);
} else {
  fs.writeFileSync(target, source);
  console.log(`Wrote ${path.relative(root, target)}`);
}
