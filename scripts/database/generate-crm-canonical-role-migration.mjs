#!/usr/bin/env node
// Generates database/platform/migrations/058_crm_canonical_system_role_permissions.sql
// from the canonical ROLE_TEMPLATES, so the migration that reconciles
// existing tenants' built-in roles can never disagree with what a newly
// bootstrapped tenant receives. packages/permissions/tests/crm-role-matrix.test.mjs
// fails if the committed migration and the templates drift apart.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ROLE_TEMPLATES } from "../../packages/permissions/src/roles.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
export const MIGRATION_PATH = path.join(root, "database/platform/migrations/058_crm_canonical_system_role_permissions.sql");
// Roles whose template is "every permission": their CRM set is every crm.*
// key in the live catalog, so a future CRM permission reaches them too.
export const ALL_CRM_SLUGS = ["organization_owner", "system_administrator"];

// CRM permissions added by this correction: registered in the catalog
// first (role_permissions.permission_key REFERENCES permissions(key)).
export const NEW_CRM_PERMISSIONS = Object.freeze([
  ["crm.leads.view_all", "View all CRM Leads", "See every Lead in the permitted companies/branches regardless of owner. Does not widen Opportunities, Accounts or Activities."],
  ["crm.customers.view_all", "View all customer Accounts", "See every customer Account (not prospects), its Contacts and the Activities logged on them, regardless of owner."],
]);

export function canonicalCrmGrants() {
  const grants = [];
  for (const template of ROLE_TEMPLATES) {
    if (ALL_CRM_SLUGS.includes(template.slug)) continue;
    for (const key of template.permissions) if (key.startsWith("crm.")) grants.push([template.slug, key]);
  }
  return grants.sort((a, b) => a[0].localeCompare(b[0]) || a[1].localeCompare(b[1]));
}

export function buildMigration() {
  const grants = canonicalCrmGrants();
  const slugs = ROLE_TEMPLATES.map((template) => template.slug).sort();
  return `BEGIN;

-- CRM role hierarchy correction (generated by
-- scripts/database/generate-crm-canonical-role-migration.mjs from the
-- canonical ROLE_TEMPLATES in packages/permissions/src/roles.js — do not edit
-- by hand; regenerate instead).
--
-- Built-in (is_system) roles cannot be edited from the UI, and bootstrap only
-- ever inserts, so older tenants kept whatever CRM grants earlier migrations
-- gave them (036/037 granted Contact/Account sensitive access to nine roles
-- the templates never included) while new tenants got only the templates.
-- This makes every tenant's built-in roles carry exactly the canonical CRM
-- permissions: missing grants are added and CRM grants outside the canonical
-- set are removed. Only crm.* keys on is_system roles are touched — custom
-- roles and every non-CRM permission are left exactly as they are.
-- Idempotent: running it again changes nothing.
--
-- Notable changes: Sales Manager loses crm.records.view_all (now team-scoped
-- through crm_sales_teams); Company Administrator keeps only crm.view and
-- crm.reports.view; Contact/Account sensitive access is granted consistently
-- to the CRM/sales roles that work with customer contacts. Resource-specific
-- visibility replaces the umbrella crm.records.view_all where a role needs
-- only one kind of record: Marketing -> crm.leads.view_all, Customer Success
-- -> crm.customers.view_all, Partner Manager -> partner relationships
-- (crm.partners.manage); Auditor and Read-only gain company-wide CRM read.
-- To reverse, re-run the previous grants (036/037 and the prior templates);
-- no data other than role_permissions rows is affected.

INSERT INTO permissions (key, name, category, description) VALUES
${NEW_CRM_PERMISSIONS.map(([key, name, description]) => `  ('${key}', '${name}', 'CRM', '${description}')`).join(",\n")}
ON CONFLICT (key) DO UPDATE SET name=EXCLUDED.name, category=EXCLUDED.category, description=EXCLUDED.description;

CREATE TEMP TABLE crm_canonical_role_permissions (slug text NOT NULL, permission_key text NOT NULL) ON COMMIT DROP;

INSERT INTO crm_canonical_role_permissions (slug, permission_key) VALUES
${grants.map(([slug, key]) => `  ('${slug}', '${key}')`).join(",\n")};

-- Organisation Owner and System Administrator: every CRM permission in the catalog.
INSERT INTO crm_canonical_role_permissions (slug, permission_key)
SELECT role_slug.slug, permission.key
  FROM (VALUES ${ALL_CRM_SLUGS.map((slug) => `('${slug}')`).join(", ")}) AS role_slug(slug)
 CROSS JOIN permissions permission
 WHERE permission.key LIKE 'crm.%';

-- Remove CRM grants on built-in roles that the canonical matrix does not include.
DELETE FROM role_permissions role_permission
 USING roles role
 WHERE role_permission.role_id = role.id
   AND role.is_system = true
   AND role.slug IN (${slugs.map((slug) => `'${slug}'`).join(", ")})
   AND role_permission.permission_key LIKE 'crm.%'
   AND NOT EXISTS (
     SELECT 1 FROM crm_canonical_role_permissions canonical
      WHERE canonical.slug = role.slug AND canonical.permission_key = role_permission.permission_key
   );

-- Add the canonical CRM grants that are missing (only for permissions that exist in the catalog).
INSERT INTO role_permissions (role_id, permission_key)
SELECT role.id, canonical.permission_key
  FROM roles role
  JOIN crm_canonical_role_permissions canonical ON canonical.slug = role.slug
  JOIN permissions permission ON permission.key = canonical.permission_key
 WHERE role.is_system = true
ON CONFLICT DO NOTHING;

COMMIT;
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(MIGRATION_PATH, buildMigration());
  console.log(`Wrote ${path.relative(root, MIGRATION_PATH)} (${canonicalCrmGrants().length} explicit grants).`);
}
