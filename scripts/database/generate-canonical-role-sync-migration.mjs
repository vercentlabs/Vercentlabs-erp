#!/usr/bin/env node
// Canonical built-in (system) role synchronization.
//
// packages/permissions/src/roles.js (ROLE_TEMPLATES) is the single source of
// truth for built-in roles. Bootstrap only ever INSERTs, so an organization
// created before a template changed keeps its old grants forever unless a
// migration reconciles it. This generator produces that migration from the
// CURRENT templates — for every role, not one module at a time (it supersedes
// the CRM-only generator behind migration 058, which stays as history).
//
// The generated SQL, per organization and per built-in slug:
//   - provisions a missing built-in role (never over a custom role that
//     already uses the slug);
//   - for is_system roles only: snapshots the pre-sync state, updates
//     canonical metadata, adds missing canonical grants, removes
//     non-canonical grants, bumps the version and snapshots the result;
//   - never touches custom roles, role ids, or user_role_assignments.
// Deterministic (sorted, no timestamps), idempotent (a second run changes
// nothing and records no new versions) and transaction-wrapped.
//
// Usage when a template changes:
//   node scripts/database/generate-canonical-role-sync-migration.mjs --write
//     → writes database/platform/migrations/<next>_canonical_system_role_sync.sql
//       and points packages/permissions/role-templates.lock.json at it.
// Never edit a shipped sync migration; generate a new one.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { ROLE_TEMPLATES } from "../../packages/permissions/src/roles.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
export const MIGRATIONS_DIR = path.join(root, "database/platform/migrations");
export const SYNC_MIGRATION_SUFFIX = "_canonical_system_role_sync.sql";

const literal = (value) => `'${String(value).replaceAll("'", "''")}'`;

export function canonicalRoleRows(templates = ROLE_TEMPLATES) {
  return [...templates].sort((a, b) => a.slug.localeCompare(b.slug));
}

export function canonicalGrantRows(templates = ROLE_TEMPLATES) {
  return canonicalRoleRows(templates).flatMap((template) => [...new Set(template.permissions)].sort().map((key) => [template.slug, key]));
}

export function buildMigration(templates = ROLE_TEMPLATES) {
  const roles = canonicalRoleRows(templates);
  const grants = canonicalGrantRows(templates);
  const roleValues = roles
    .map((role) => `  (${[role.slug, role.name, role.description, role.moduleKey, role.riskLevel].map(literal).join(", ")}, ${role.assignable})`)
    .join(",\n");
  const grantValues = grants.map(([slug, key]) => `  (${literal(slug)}, ${literal(key)})`).join(",\n");
  return `BEGIN;

-- Canonical built-in role synchronization — generated by
-- scripts/database/generate-canonical-role-sync-migration.mjs from
-- packages/permissions/src/roles.js ROLE_TEMPLATES. Do not edit by hand:
-- regenerate into a NEW migration when a template changes.
--
-- Reconciles every organization's built-in (is_system) roles to the current
-- templates: provisions missing built-in roles, updates canonical metadata,
-- adds missing grants and removes non-canonical grants. Role ids,
-- user_role_assignments, custom roles and existing role_version_snapshots are
-- never modified; every changed role gets a before and an after snapshot.
-- Idempotent: running it again changes nothing. ${roles.length} roles, ${grants.length} grants.

CREATE TEMP TABLE canonical_system_roles (
  slug text PRIMARY KEY, name text NOT NULL, description text NOT NULL,
  module_key text NOT NULL, risk_level text NOT NULL, assignable boolean NOT NULL
) ON COMMIT DROP;

INSERT INTO canonical_system_roles (slug, name, description, module_key, risk_level, assignable) VALUES
${roleValues};

CREATE TEMP TABLE canonical_system_role_permissions (
  slug text NOT NULL, permission_key text NOT NULL, PRIMARY KEY (slug, permission_key)
) ON COMMIT DROP;

INSERT INTO canonical_system_role_permissions (slug, permission_key) VALUES
${grantValues};

-- A canonical key missing from the permission catalogue is a release defect:
-- fail loudly instead of silently granting less than the template says.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM canonical_system_role_permissions canonical
    WHERE NOT EXISTS (SELECT 1 FROM permissions permission WHERE permission.key = canonical.permission_key)
  ) THEN
    RAISE EXCEPTION 'canonical role sync: permission key missing from permissions catalogue';
  END IF;
END $$;

-- 1. Provision built-in roles an organization is missing. A custom role that
--    already owns the slug is left alone (ON CONFLICT) and is not synced.
INSERT INTO roles (organization_id, name, slug, description, is_system, status, module_key, template_key, assignable, risk_level, version)
SELECT organization.id, canonical.name, canonical.slug, canonical.description, true, 'active',
       canonical.module_key, canonical.slug, canonical.assignable, canonical.risk_level, 1
  FROM organizations organization
  CROSS JOIN canonical_system_roles canonical
ON CONFLICT (organization_id, slug) DO NOTHING;

-- 2. The built-in roles in scope: is_system rows whose slug is canonical.
CREATE TEMP TABLE canonical_sync_targets ON COMMIT DROP AS
SELECT role.id AS role_id, role.organization_id, role.slug
  FROM roles role
  JOIN canonical_system_roles canonical ON canonical.slug = role.slug
 WHERE role.is_system = true;

-- 3. Which of them actually differ from the template.
CREATE TEMP TABLE canonical_sync_changed ON COMMIT DROP AS
SELECT target.role_id, target.organization_id
  FROM canonical_sync_targets target
  JOIN roles role ON role.id = target.role_id
  JOIN canonical_system_roles canonical ON canonical.slug = target.slug
 WHERE role.name IS DISTINCT FROM canonical.name
    OR role.description IS DISTINCT FROM canonical.description
    OR role.module_key IS DISTINCT FROM canonical.module_key
    OR role.risk_level IS DISTINCT FROM canonical.risk_level
    OR role.assignable IS DISTINCT FROM canonical.assignable
    OR role.template_key IS DISTINCT FROM canonical.slug
    OR role.status <> 'active'
    OR EXISTS (
      SELECT 1 FROM canonical_system_role_permissions grant_row
       WHERE grant_row.slug = target.slug
         AND NOT EXISTS (SELECT 1 FROM role_permissions existing WHERE existing.role_id = target.role_id AND existing.permission_key = grant_row.permission_key)
    )
    OR EXISTS (
      SELECT 1 FROM role_permissions existing
       WHERE existing.role_id = target.role_id
         AND NOT EXISTS (SELECT 1 FROM canonical_system_role_permissions grant_row WHERE grant_row.slug = target.slug AND grant_row.permission_key = existing.permission_key)
    );

-- 4. Evidence of the pre-sync state (skipped if that version is already recorded).
INSERT INTO role_version_snapshots (organization_id, role_id, version, snapshot, reason, created_by)
SELECT role.organization_id, role.id, role.version,
       jsonb_build_object(
         'name', role.name, 'slug', role.slug, 'description', role.description,
         'moduleKey', role.module_key, 'riskLevel', role.risk_level, 'assignable', role.assignable,
         'permissionKeys', COALESCE((SELECT jsonb_agg(existing.permission_key ORDER BY existing.permission_key) FROM role_permissions existing WHERE existing.role_id = role.id), '[]'::jsonb)
       ),
       'Before canonical system role synchronization', NULL
  FROM roles role
  JOIN canonical_sync_changed changed ON changed.role_id = role.id
ON CONFLICT (organization_id, role_id, version) DO NOTHING;

-- 5. Canonical metadata + version bump for changed roles only.
UPDATE roles role
   SET name = canonical.name, description = canonical.description, module_key = canonical.module_key,
       risk_level = canonical.risk_level, assignable = canonical.assignable, template_key = canonical.slug,
       status = 'active', version = role.version + 1, updated_at = now()
  FROM canonical_sync_changed changed, canonical_system_roles canonical
 WHERE role.id = changed.role_id AND canonical.slug = role.slug;

-- 6. Remove grants that are not canonical (built-in roles only).
DELETE FROM role_permissions existing
 USING canonical_sync_targets target
 WHERE existing.role_id = target.role_id
   AND NOT EXISTS (
     SELECT 1 FROM canonical_system_role_permissions grant_row
      WHERE grant_row.slug = target.slug AND grant_row.permission_key = existing.permission_key
   );

-- 7. Add missing canonical grants.
INSERT INTO role_permissions (role_id, permission_key)
SELECT target.role_id, grant_row.permission_key
  FROM canonical_sync_targets target
  JOIN canonical_system_role_permissions grant_row ON grant_row.slug = target.slug
ON CONFLICT DO NOTHING;

-- 8. Evidence of the synchronized state at the new version.
INSERT INTO role_version_snapshots (organization_id, role_id, version, snapshot, reason, created_by)
SELECT role.organization_id, role.id, role.version,
       jsonb_build_object(
         'name', role.name, 'slug', role.slug, 'description', role.description,
         'moduleKey', role.module_key, 'riskLevel', role.risk_level, 'assignable', role.assignable,
         'permissionKeys', COALESCE((SELECT jsonb_agg(existing.permission_key ORDER BY existing.permission_key) FROM role_permissions existing WHERE existing.role_id = role.id), '[]'::jsonb)
       ),
       'Canonical system role synchronization', NULL
  FROM roles role
  JOIN canonical_sync_changed changed ON changed.role_id = role.id
ON CONFLICT (organization_id, role_id, version) DO NOTHING;

COMMIT;
`;
}

export function listSyncMigrations(directory = MIGRATIONS_DIR) {
  return fs.readdirSync(directory).filter((name) => name.endsWith(SYNC_MIGRATION_SUFFIX)).sort();
}

export function nextMigrationName(directory = MIGRATIONS_DIR) {
  const numbers = fs.readdirSync(directory).map((name) => Number(name.match(/^(\d+)_/)?.[1])).filter(Number.isFinite);
  const next = String(Math.max(0, ...numbers) + 1).padStart(3, "0");
  return `${next}${SYNC_MIGRATION_SUFFIX}`;
}

if (import.meta.url === pathToFileURL(process.argv[1] || "").href) {
  if (!process.argv.includes("--write")) {
    process.stdout.write(buildMigration());
  } else {
    const sql = buildMigration();
    const latest = listSyncMigrations().at(-1);
    if (latest && fs.readFileSync(path.join(MIGRATIONS_DIR, latest), "utf8").replace(/\r\n/g, "\n") === sql) {
      console.log(`${latest} already matches the current templates; nothing to write.`);
    } else {
      const name = nextMigrationName();
      fs.writeFileSync(path.join(MIGRATIONS_DIR, name), sql);
      console.log(`Wrote database/platform/migrations/${name}`);
      console.log(`Now run: node scripts/access/role-template-lock.mjs --write --synchronized-by database/platform/migrations/${name}`);
    }
  }
}
