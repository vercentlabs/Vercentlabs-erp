const COMMON_PASSWORD_SET = new Set(COMMON_PASSWORDS.map((entry) => entry.toLowerCase()));

/** True if the (already-normalized) password is a well-known common/compromised value and should be rejected. */
export function isCommonPassword(normalizedPassword: string): boolean {
  return COMMON_PASSWORD_SET.has(normalizedPassword.toLowerCase());
}
