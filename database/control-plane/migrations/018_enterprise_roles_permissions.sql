-- assignments. Force every active session to rebuild its cumulative permission set.
UPDATE sessions
SET revoked_at=COALESCE(revoked_at,now()),
    revoked_reason=COALESCE(revoked_reason,'enterprise_rbac_migrated')
WHERE revoked_at IS NULL
  AND EXISTS (
    SELECT 1 FROM organization_memberships membership
    WHERE membership.user_id=sessions.user_id
  );

