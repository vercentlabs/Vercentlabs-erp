       jsonb_build_object('name',r.name,'slug',r.slug,'description',r.description,'moduleKey',r.module_key,'riskLevel',r.risk_level,'assignable',r.assignable,'permissionKeys',COALESCE((SELECT jsonb_agg(rp.permission_key ORDER BY rp.permission_key) FROM role_permissions rp WHERE rp.role_id=r.id),'[]'::jsonb)),
